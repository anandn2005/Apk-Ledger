/**
 * Tabular number OpenType feature tag ("tnum") ensures identical digit widths
 * across all numerical values (Amounts, Dashboard Totals, Quantities), aligning
 * vertically on decimal points and eliminating jagged financial lists.
 */
const val TabularFiguresFeature = "tnum"

fun TextStyle.tabularNumbers(): TextStyle = this.copy(
    fontFeatureSettings = TabularFiguresFeature
)

